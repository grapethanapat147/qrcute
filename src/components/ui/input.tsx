/** htmlFor เป็น required เพื่อบังคับให้ทุก label ผูกกับ input จริง ๆ */
export type LabelProps = React.ComponentProps<"label"> & { htmlFor: string };

export function Label({ className, ...props }: LabelProps) {
  return (
    // biome-ignore lint/a11y/noLabelWithoutControl: htmlFor เป็น required prop และส่งผ่าน spread — rule มองไม่เห็นตอน static analysis
    <label
      data-slot="label"
      className={cn(
        "text-sm font-medium leading-none peer-disabled:cursor-not-allowed peer-disabled:opacity-70",
        className,
      )}
      {...props}
    />
  );
}
